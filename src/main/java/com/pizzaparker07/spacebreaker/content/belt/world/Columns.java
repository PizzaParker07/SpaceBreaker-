package com.pizzaparker07.spacebreaker.content.belt.world;

import com.pizzaparker07.spacebreaker.content.worldgen.PlanetChunkGenerator;
import com.pizzaparker07.spacebreaker.content.worldgen.PlanetTerrain;
import net.minecraft.core.BlockPos;
import net.minecraft.util.Mth;
import net.minecraft.world.level.WorldGenLevel;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.chunk.ChunkGenerator;
import net.minecraft.world.level.levelgen.Heightmap;
import net.minecraft.world.level.levelgen.XoroshiroRandomSource;
import net.minecraft.world.level.levelgen.synth.SimplexNoise;

import java.util.concurrent.ConcurrentHashMap;

/**
 * Column edits for surface features that reshape ground generated by the planet engine: raising or lowering a column
 * while keeping its soil layers on top, replacing the top blocks, and seeded noise shared by every chunk (so shapes line
 * up across chunk borders). Everything runs inside the feature's own chunk.
 */
public final class Columns {
    /** Blocks of the original column top carried along when a column moves. */
    public static final int CARRY = 4;
    private static final ConcurrentHashMap<Long, SimplexNoise> NOISE = new ConcurrentHashMap<>();

    private Columns() {
    }

    /** The planet terrain behind a chunk generator, or null for other generators. */
    public static PlanetTerrain terrain(ChunkGenerator generator) {
        return generator instanceof PlanetChunkGenerator p ? p.terrain() : null;
    }

    /** A noise field for a world seed and salt (cached; SimplexNoise is read-only after construction). */
    public static SimplexNoise noise(long seed, int salt) {
        long key = seed * 31 + salt;
        SimplexNoise n = NOISE.get(key);
        if (n == null) {
            if (NOISE.size() > 256) {
                NOISE.clear();
            }
            n = new SimplexNoise(new XoroshiroRandomSource(seed ^ (0x0D7E8L * salt + salt)));
            NOISE.put(key, n);
        }
        return n;
    }

    /** Fractal noise in about -1..1. */
    public static double fbm(SimplexNoise n, double x, double z, int octaves) {
        double sum = 0;
        double amp = 1;
        double norm = 0;
        double f = 1;
        for (int i = 0; i < octaves; i++) {
            sum += n.getValue(x * f + i * 13.7, z * f - i * 7.3) * amp;
            norm += amp;
            amp *= 0.5;
            f *= 2.01;
        }
        return sum / norm;
    }

    /**
     * y of the top non-air block of a column. Starts from the generation heightmap but scans the blocks themselves, because
     * the heightmap is not reliably updated while features dig and build inside one generation step.
     */
    public static int top(WorldGenLevel level, int x, int z) {
        int start = Math.min(level.getMaxBuildHeight() - 1, level.getHeight(Heightmap.Types.WORLD_SURFACE_WG, x, z) + 24);
        BlockPos.MutableBlockPos p = new BlockPos.MutableBlockPos(x, start, z);
        int min = level.getMinBuildHeight();
        while (p.getY() > min && level.getBlockState(p).isAir()) {
            p.move(0, -1, 0);
        }
        return p.getY();
    }

    /**
     * Moves the ground surface of a column by {@code dy} blocks (negative digs down, positive builds up), keeping the top
     * {@link #CARRY} blocks (soil over rock) as the new top. New ground below the carried layers is {@code fill}.
     *
     * @return the new top y
     */
    public static int shift(WorldGenLevel level, int x, int z, int dy, BlockState fill) {
        int y = top(level, x, z);
        if (dy == 0 || y <= level.getMinBuildHeight() + CARRY + 2) {
            return y;
        }
        BlockPos.MutableBlockPos p = new BlockPos.MutableBlockPos();
        BlockState[] carried = new BlockState[CARRY];
        for (int i = 0; i < CARRY; i++) {
            carried[i] = level.getBlockState(p.set(x, y - i, z));
        }
        int maxY = level.getMaxBuildHeight() - 2;
        int ny = Mth.clamp(y + dy, level.getMinBuildHeight() + CARRY + 2, maxY);
        if (ny < y) {
            for (int yy = y; yy > ny; yy--) {
                level.setBlock(p.set(x, yy, z), Blocks.AIR.defaultBlockState(), 2);
            }
        } else {
            for (int yy = y - CARRY + 1; yy <= ny - CARRY; yy++) {
                level.setBlock(p.set(x, yy, z), fill, 2);
            }
        }
        for (int i = 0; i < CARRY; i++) {
            level.setBlock(p.set(x, ny - i, z), carried[i], 2);
        }
        return ny;
    }

    /** Replaces the top {@code depth} solid blocks of a column. */
    public static void paint(WorldGenLevel level, int x, int z, int depth, BlockState block) {
        int y = top(level, x, z);
        BlockPos.MutableBlockPos p = new BlockPos.MutableBlockPos();
        for (int i = 0; i < depth; i++) {
            p.set(x, y - i, z);
            if (!level.getBlockState(p).isAir()) {
                level.setBlock(p, block, 2);
            }
        }
    }

    /** Smoothstep 0..1. */
    public static double smooth(double t) {
        t = Mth.clamp(t, 0, 1);
        return t * t * (3 - 2 * t);
    }

    /** A uniform double in [0, 1) from a hash and stream index. */
    public static double unit(long h, int i) {
        long z = h * 0x9E3779B97F4A7C15L + i * 0xBF58476D1CE4E5B9L + 0x632BE59BD9B4E019L;
        z = (z ^ (z >>> 30)) * 0xBF58476D1CE4E5B9L;
        z = (z ^ (z >>> 27)) * 0x94D049BB133111EBL;
        z ^= z >>> 31;
        return (z >>> 11) * 0x1.0p-53;
    }

    /** Hash of a grid cell. */
    public static long cell(long seed, int salt, int gx, int gz) {
        return (long) (unit(seed ^ ((long) gx * 0x632BE5AB) ^ ((long) gz * 0x85157AF5) ^ salt, 7) * Long.MAX_VALUE);
    }
}
