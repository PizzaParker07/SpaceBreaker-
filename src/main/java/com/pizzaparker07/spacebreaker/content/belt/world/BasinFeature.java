package com.pizzaparker07.spacebreaker.content.belt.world;

import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import com.pizzaparker07.spacebreaker.content.worldgen.PlanetTerrain;
import net.minecraft.util.Mth;
import net.minecraft.world.level.WorldGenLevel;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.levelgen.feature.Feature;
import net.minecraft.world.level.levelgen.feature.FeaturePlaceContext;
import net.minecraft.world.level.levelgen.feature.configurations.FeatureConfiguration;
import net.minecraft.world.level.levelgen.synth.SimplexNoise;

import java.util.Optional;

/**
 * One giant impact basin far larger than the planet engine's crater classes, like Rheasilvia on Vesta (500 km across on
 * a body 525 km wide): a raised, wobbly rim, a steep terraced wall, a broad flat floor with concentric scarps, and a
 * huge central mountain. Vertical sizes are compressed to fit the build height. Shapes the existing surface column by
 * column, so the smaller craters generated by the terrain profile stay visible inside it.
 *
 * @param x          basin centre x
 * @param latitude   basin centre latitude (degrees; -90 = south pole)
 * @param radius     rim radius in blocks
 * @param depth      floor depth below the surroundings
 * @param rim        rim height
 * @param peak       central mountain height above the floor
 * @param peakRadius central mountain base radius in basin radii
 * @param terraces   steps in the wall
 * @param wall       width of the wall in basin radii
 * @param rings      height of the concentric ring scarps on the floor
 * @param rock       ground used to build up the rim and mountain under the carried soil
 * @param floorSoil  optional soil on the floor (impact melt, slumped debris)
 * @param band       optional second rock: the wall and the central mountain show layers of {@code rock} and {@code band}
 * @param floorExtent how far out the floor soil reaches, in basin radii (default 0.7)
 */
public class BasinFeature extends Feature<BasinFeature.Config> {
    public record Config(double x, double latitude, double radius, double depth, double rim, double peak, double peakRadius, int terraces,
                         double wall, double rings, BlockState rock, Optional<BlockState> floorSoil,
                         Optional<BlockState> band, double floorExtent) implements FeatureConfiguration {
        public static final Codec<Config> CODEC = RecordCodecBuilder.create(i -> i.group(
                Codec.DOUBLE.optionalFieldOf("x", 0.0).forGetter(Config::x),
                Codec.DOUBLE.optionalFieldOf("latitude", -90.0).forGetter(Config::latitude),
                Codec.DOUBLE.fieldOf("radius").forGetter(Config::radius),
                Codec.DOUBLE.optionalFieldOf("depth", 36.0).forGetter(Config::depth),
                Codec.DOUBLE.optionalFieldOf("rim", 14.0).forGetter(Config::rim),
                Codec.DOUBLE.optionalFieldOf("peak", 60.0).forGetter(Config::peak),
                Codec.DOUBLE.optionalFieldOf("peak_radius", 0.2).forGetter(Config::peakRadius),
                Codec.INT.optionalFieldOf("terraces", 4).forGetter(Config::terraces),
                Codec.DOUBLE.optionalFieldOf("wall", 0.2).forGetter(Config::wall),
                Codec.DOUBLE.optionalFieldOf("rings", 1.6).forGetter(Config::rings),
                BlockState.CODEC.fieldOf("rock").forGetter(Config::rock),
                BlockState.CODEC.optionalFieldOf("floor_soil").forGetter(Config::floorSoil),
                BlockState.CODEC.optionalFieldOf("band").forGetter(Config::band),
                Codec.DOUBLE.optionalFieldOf("floor_extent", 0.7).forGetter(Config::floorExtent)
        ).apply(i, Config::new));

        public Config(double x, double latitude, double radius, double depth, double rim, double peak, double peakRadius, int terraces,
                      double wall, double rings, BlockState rock, Optional<BlockState> floorSoil, Optional<BlockState> band) {
            this(x, latitude, radius, depth, rim, peak, peakRadius, terraces, wall, rings, rock, floorSoil, band, 0.7);
        }
    }

    public BasinFeature() {
        super(Config.CODEC);
    }

    /** z of the basin centre for a terrain (latitude -> z, south positive). */
    public static double centreZ(PlanetTerrain t, Config cfg) {
        return -cfg.latitude() / 90.0 * t.profile().poleDistance();
    }

    /** Normalized distance from the basin centre (1 = rim crest), with a wobbly outline. */
    public static double distance(PlanetTerrain t, Config cfg, double x, double z) {
        double dx = x - cfg.x();
        double dz = z - centreZ(t, cfg);
        double d = Math.sqrt(dx * dx + dz * dz);
        double ang = Math.atan2(dz, dx);
        SimplexNoise n = Columns.noise(t.seed(), 57);
        double wob = 1 + 0.06 * n.getValue(Math.cos(ang) * 2.1, Math.sin(ang) * 2.1) + 0.025 * n.getValue(Math.cos(ang) * 7 + 40, Math.sin(ang) * 7);
        return d / (cfg.radius() * wob);
    }

    /** Height change of the ground at a column (blocks). */
    public static double offset(PlanetTerrain t, Config cfg, double x, double z) {
        double s = distance(t, cfg, x, z);
        if (s > 1.7) {
            return 0;
        }
        SimplexNoise n = Columns.noise(t.seed(), 58);
        // outer ejecta swell and the rim crest
        double rim = cfg.rim() * Math.exp(-Math.pow((s - 1) / (s < 1 ? 0.06 : 0.25), 2));
        // wall: from the crest down to the floor between s = 1 and s = 1 - wall, in terraces
        double wall = Columns.smooth((1 - s) / cfg.wall());
        if (cfg.terraces() > 1) {
            double steps = wall * cfg.terraces();
            double k = Math.floor(steps);
            double f = steps - k;
            wall = (k + Columns.smooth((f - 0.65) / 0.35)) / cfg.terraces();
        }
        double floor = -cfg.depth() * wall;
        // concentric scarps on the floor (the basin's ring faults), low and broken
        double ring = 0;
        if (s < 1 - cfg.wall() * 0.9 && s > cfg.peakRadius() && cfg.rings() > 0) {
            double r = Math.sin(s * 30 + n.getValue(x / 300.0, z / 300.0) * 2);
            ring = cfg.rings() * Columns.smooth((r - 0.2) / 0.8) * (0.5 + 0.5 * n.getValue(x / 90.0, z / 90.0));
        }
        // the central mountain: a broad, lumpy massif
        double peak = 0;
        double pr = cfg.peakRadius();
        if (s < pr) {
            double u = 1 - s / pr;
            double lumps = 0.75 + 0.35 * Columns.fbm(n, x / 70.0 + 9, z / 70.0 - 9, 3);
            peak = cfg.peak() * Math.pow(u, 1.4) * Mth.clamp(lumps, 0.4, 1.2);
        }
        return rim + floor + ring + peak;
    }

    @Override
    public boolean place(FeaturePlaceContext<Config> ctx) {
        PlanetTerrain t = Columns.terrain(ctx.chunkGenerator());
        if (t == null) {
            return false;
        }
        Config cfg = ctx.config();
        WorldGenLevel level = ctx.level();
        int x0 = ctx.origin().getX() & ~15;
        int z0 = ctx.origin().getZ() & ~15;
        double reach = cfg.radius() * 1.9;
        if (Math.abs(x0 + 8 - cfg.x()) > reach || Math.abs(z0 + 8 - centreZ(t, cfg)) > reach) {
            return false;
        }
        boolean any = false;
        SimplexNoise n = Columns.noise(t.seed(), 59);
        for (int dx = 0; dx < 16; dx++) {
            for (int dz = 0; dz < 16; dz++) {
                int x = x0 + dx;
                int z = z0 + dz;
                double s = distance(t, cfg, x, z);
                int dy = (int) Math.round(offset(t, cfg, x + 0.5, z + 0.5));
                int top = Integer.MIN_VALUE;
                if (dy != 0) {
                    top = Columns.shift(level, x, z, dy, cfg.rock());
                    any = true;
                }
                if (cfg.floorSoil().isPresent() && s < cfg.floorExtent() && s > cfg.peakRadius() * 0.8) {
                    if (top == Integer.MIN_VALUE) {
                        top = Columns.top(level, x, z);
                    }
                    Columns.paint(level, x, top, z, 1, cfg.floorSoil().get());
                }
                if (cfg.band().isPresent()) {
                    band(level, cfg, n, x, z, s);
                }
            }
        }
        return any;
    }

    /**
     * Exposed layers: on the wall, wavy bands of the two rocks (two per terrace) broken by slumped soil; on the central
     * mountain, streaks of the band rock over bare rock.
     */
    private static void band(WorldGenLevel level, Config cfg, SimplexNoise n, int x, int z, double s) {
        double wobble = n.getValue(x / 45.0, z / 45.0);
        if (s < 1.0 && s > 1 - cfg.wall()) {
            if (n.getValue(x / 11.0 + 31, z / 11.0) < -0.35) {
                return;
            }
            double k = (1 - s) / cfg.wall() * Math.max(1, cfg.terraces()) * 2 + wobble * 0.9;
            Columns.paint(level, x, z, 2, ((int) Math.floor(k) & 1) == 0 ? cfg.rock() : cfg.band().get());
        } else if (s < cfg.peakRadius() * 0.85) {
            double streak = Math.sin((x * 0.6 + z) / 9.0 + wobble * 3);
            Columns.paint(level, x, z, 2, streak > 0.55 ? cfg.band().get() : cfg.rock());
        }
    }
}
