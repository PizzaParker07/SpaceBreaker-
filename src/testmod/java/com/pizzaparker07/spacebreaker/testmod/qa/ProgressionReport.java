package com.pizzaparker07.spacebreaker.testmod.qa;

import com.pizzaparker07.spacebreaker.Spacebreaker;
import com.pizzaparker07.spacebreaker.content.rocketry.nav.Location;
import com.pizzaparker07.spacebreaker.content.rocketry.nav.Locations;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.Item;
import net.minecraft.world.level.Level;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeSet;

/** Turns a {@link ProgressionModel} into the Markdown report copied to docs/QA.md. */
final class ProgressionReport {
    private ProgressionReport() {
    }

    /** Items that are meant to exist only in creative mode / for tests. */
    static final java.util.Set<String> CREATIVE_ONLY = java.util.Set.of("propellant_cartridge");

    record Goal(String title, String fact) {
    }

    static List<Goal> goals() {
        return List.of(
                new Goal("First rocket launch (reaches Earth orbit, return not required)", ProgressionModel.landed(Location.EARTH_ORBIT.dimension())),
                new Goal("Earth orbit and back", ProgressionModel.world(Location.EARTH_ORBIT.dimension())),
                new Goal("Moon landing and return", ProgressionModel.world(Location.MOON_SURFACE.dimension())),
                new Goal("Mars landing and return", "world:spacebreaker:mars"));
    }

    static String render(ProgressionModel m) {
        StringBuilder out = new StringBuilder();
        out.append("<!-- generated by the GameTest qa/ProgressionAuditTests (realism ").append(m.realism).append(") -->\n");
        out.append("## Progression model summary\n\n");
        out.append("- recipes analysed: ").append(m.rules.size()).append(", special recipes skipped: ").append(m.specialRecipes.size()).append('\n');
        out.append("- worlds: ").append(m.worlds.size()).append(", technologies: ").append(m.techTree.size()).append(", model steps: ").append(m.step).append('\n');
        out.append("- machines that lock themselves until researched: ").append(String.join(", ",
                m.machinesThatEnforce.stream().map(ResourceLocation::getPath).toList())).append("\n\n");

        out.append("## Goals\n\n");
        for (Goal g : goals()) {
            boolean ok = m.has(g.fact());
            out.append("### ").append(ok ? "✅ " : "❌ ").append(g.title()).append("\n\n");
            if (!ok) {
                out.append("Not reachable in a fresh survival world.\n\n");
                continue;
            }
            List<String> techs = new ArrayList<>();
            List<String> worlds = new ArrayList<>();
            List<String> machines = new ArrayList<>();
            for (var e : m.path(g.fact())) {
                String f = e.getKey();
                var fact = e.getValue();
                if (f.startsWith("tech:")) {
                    techs.add("step " + fact.step() + ": **" + f.substring(5 + Spacebreaker.MOD_ID.length() + 1) + "** — " + fact.reason());
                } else if (f.startsWith("world:") && !f.equals("world:minecraft:overworld")) {
                    worlds.add("step " + fact.step() + ": " + f.substring(6) + " — " + fact.reason());
                } else if (f.startsWith("item:spacebreaker:") && isMachine(f)) {
                    machines.add(f.substring(18));
                }
            }
            out.append("Research in this order:\n\n");
            techs.forEach(t -> out.append("1. ").append(t).append('\n'));
            if (!machines.isEmpty()) {
                out.append("\nMachines built on the way: ").append(String.join(", ", new TreeSet<>(machines))).append('\n');
            }
            if (!worlds.isEmpty()) {
                out.append("\nFlights:\n\n");
                worlds.forEach(w -> out.append("- ").append(w).append('\n'));
            }
            out.append('\n');
        }

        out.append("## Technologies in the order a fresh world can learn them\n\n");
        m.facts.forEach((k, v) -> {
            if (k.startsWith("tech:")) {
                out.append("- step ").append(v.step()).append(": `").append(k.substring(5 + Spacebreaker.MOD_ID.length() + 1)).append("` — ")
                        .append(v.reason()).append('\n');
            }
        });
        out.append('\n');
        out.append("## Technologies that cannot be learned\n\n");
        int blocked = 0;
        for (var e : m.techTree.entrySet()) {
            if (!m.has(ProgressionModel.tech(e.getKey()))) {
                blocked++;
                out.append("- `").append(e.getKey().getPath()).append("` (tier ").append(e.getValue().tier()).append("): ")
                        .append(m.whyNot(e.getKey())).append('\n');
            }
        }
        if (blocked == 0) {
            out.append("None.\n");
        }
        out.append('\n');

        out.append("## Worlds\n\n| World | Reached | How | Survival when first reached |\n|---|---|---|---|\n");
        for (var w : m.worlds.values()) {
            String key = ProgressionModel.world(w.dim());
            var f = m.facts.get(key);
            var landed = m.facts.get(ProgressionModel.landed(w.dim()));
            String how = f != null ? "step " + f.step() + ": " + f.reason() : landed != null ? "one way only: " + landed.reason() : "—";
            out.append("| ").append(w.dim().location()).append(" | ").append(f != null ? "yes" : landed != null ? "one way" : "**no**")
                    .append(" | ").append(how.replace("|", "/")).append(" | ").append(m.survival.getOrDefault(w.dim(), w.dim() == Level.OVERWORLD ? "home" : "—"))
                    .append(" |\n");
        }
        out.append('\n');

        out.append("## Items that cannot be obtained\n\n");
        List<String> missingItems = new ArrayList<>();
        for (Item i : m.modItems()) {
            if (!m.hasItem(i) && !(i instanceof net.minecraft.world.item.SpawnEggItem) && !CREATIVE_ONLY.contains(BuiltInRegistries.ITEM.getKey(i).getPath())) {
                missingItems.add("- `" + BuiltInRegistries.ITEM.getKey(i).getPath() + "`: " + m.whyNotItem(i));
            }
        }
        out.append(missingItems.isEmpty() ? "None.\n" : String.join("\n", missingItems) + "\n");
        out.append('\n');

        if (!m.orphanLoot.isEmpty()) {
            out.append("## Loot tables no world uses\n\nThese chests give research or mod items but no dungeon definition or world maps to them:\n\n");
            m.orphanLoot.forEach(t -> out.append("- `").append(t).append("`\n"));
            out.append('\n');
        }
        if (!m.unmappedRecipeTypes.isEmpty()) {
            out.append("## Recipe types the model does not know\n\n");
            m.unmappedRecipeTypes.forEach(t -> out.append("- `").append(t).append("`\n"));
            out.append('\n');
        }
        out.append("## Special recipes (not analysed)\n\n");
        m.specialRecipes.forEach(t -> out.append("- `").append(t).append("`\n"));
        out.append('\n');
        out.append("## Missions flown by the model\n\n| Destination | Mode | Δv needed (gameplay) | Smallest rocket |\n|---|---|---|---|\n");
        for (Map.Entry<String, RocketSearch.Result> e : m.missions.entrySet()) {
            out.append("| ").append(e.getKey()).append(" | ").append(e.getValue().mode()).append(" | ").append(Math.round(e.getValue().need()))
                    .append(" | ").append(ProgressionModel.describe(e.getValue().rocket())).append(" |\n");
        }
        out.append('\n');
        out.append("## Missions the best buildable rocket cannot fly\n\n| Destination | Δv needed for a round trip (gameplay) | Best vacuum Δv of any buildable design | One way: legs (gameplay m/s) |\n|---|---|---|---|\n");
        double bestDv = m.best.stream().mapToDouble(RocketSearch.Candidate::totalDv).max().orElse(0);
        for (Location l : Locations.all()) {
            if (m.missions.containsKey(l.id()) || l.equals(Location.EARTH_SURFACE)) {
                continue;
            }
            List<Location> route = new ArrayList<>(RocketSearch.route(Location.EARTH_SURFACE, l, m.realism));
            if (route.isEmpty()) {
                out.append("| ").append(l.id()).append(" | no route | — | — |\n");
                continue;
            }
            List<String> legs = new ArrayList<>();
            for (int i = 0; i + 1 < route.size(); i++) {
                legs.add(route.get(i + 1).id() + " " + Math.round(com.pizzaparker07.spacebreaker.content.rocketry.nav.Transfers
                        .cost(route.get(i), route.get(i + 1), m.realism).orElse(-1)));
            }
            String oneWay = String.join(" → ", legs) + " = " + Math.round(RocketSearch.need(route, m.realism));
            var home = com.pizzaparker07.spacebreaker.content.rocketry.nav.MissionPlanner.homeRoute(l);
            route.addAll(home.subList(1, home.size()));
            out.append("| ").append(l.id()).append(" | ").append(Math.round(RocketSearch.need(route, m.realism))).append(" | ")
                    .append(Math.round(bestDv)).append(" | ").append(oneWay).append(" |\n");
        }
        out.append('\n');
        if (!m.notes.isEmpty()) {
            out.append("## Notes\n\n");
            m.notes.forEach(n -> out.append("- ").append(n).append('\n'));
        }
        return out.toString();
    }

    private static boolean isMachine(String fact) {
        String path = fact.substring(18);
        return ProgressionModel.MACHINE_FOR_KIND.containsValue(path) || List.of("research_lab", "combustion_generator", "solar_panel", "pumpjack",
                "atmosphere_processor", "rocket_assembler", "launch_pad", "oxygen_filler", "oxygen_distributor").contains(path);
    }

    static Path write(String name, String text) {
        Path dir = Path.of("qa");
        try {
            Files.createDirectories(dir);
            Path file = dir.resolve(name);
            Files.writeString(file, text);
            return file.toAbsolutePath();
        } catch (IOException e) {
            throw new IllegalStateException(e);
        }
    }

    @SuppressWarnings("unused")
    private static List<Location> all() {
        return Locations.all();
    }
}
